const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {spawnSync}=require('node:child_process');

test('Original AIM diagnostic APIs retain interrupted registers and safely read fatal instruction words',{timeout:180000},t=>{
 const source=process.env.ANDROID_AIM_SOURCE,target=process.env.ANDROID_AIM_CARGO_TARGET;
 if(process.platform!=='darwin'||process.arch!=='arm64'||!source||!target)return t.skip('Requires Apple Silicon, the adapted AIM source and an available Cargo target');
 const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'android-art-faults-'));t.after(()=>fs.rmSync(temporary,{recursive:true,force:true}));
 fs.mkdirSync(path.join(temporary,'src'));fs.copyFileSync(path.resolve('tests/fixtures/android-art-faults/main.rs'),path.join(temporary,'src/main.rs'));
 fs.writeFileSync(path.join(temporary,'Cargo.toml'),'[package]\nname="android-art-fault-probe"\nversion="0.0.0"\nedition="2024"\n[dependencies]\naim-linux-abi={path='+JSON.stringify(path.resolve(source,'crates/aim-linux-abi'))+'}\nlibc="0.2"\n');
 fs.copyFileSync(path.resolve(source,'Cargo.lock'),path.join(temporary,'Cargo.lock'));
 const run=(command,args,timeout=15000)=>{const result=spawnSync(command,args,{encoding:'utf8',timeout,maxBuffer:4<<20});assert.ifError(result.error);assert.equal(result.signal,null,result.stdout+result.stderr);assert.equal(result.status,0,result.stdout+result.stderr);return result;};
 run('cargo',['build','--offline','--release','-j','2','--manifest-path',path.join(temporary,'Cargo.toml'),'--target-dir',path.resolve(target)],150000);
 const binary=path.resolve(target,'release/android-art-fault-probe');
 for(const mode of ['direct','handled']){
  const result=run(binary,[mode]),text=result.stderr;
  assert.match(result.stdout,mode==='direct'?/PASS actual hardware SIGILL report preserved errno/:/PASS saved hardware fault re-raise preserved errno/);
  assert.equal((text.match(/fatal signal /g)||[]).length,1,text);
  assert.match(text,/host process \d+ pthread 0x[0-9a-f]+/);
  assert.match(text,mode==='direct'?/fatal signal 4 at pc /:/fatal signal 4 after the guest's handler; its last fault/);
  assert.match(text,/x0\s+0x0000000000001122/);assert.match(text,/x5\s+0x0000000000005566/);assert.match(text,/x16\s+0x0000000000007788/);
  const instructions=[...text.matchAll(/insn (0x[0-9a-f]+): ([0-9a-f]{8})( pc)?/g)];assert.equal(instructions.length,9,text);
  assert.equal(instructions.filter(value=>value[3]).length,1);assert.equal(instructions.find(value=>value[3])[2],'00000000');
  if(mode==='handled')assert.match(text,/instruction at interruption 0x[0-9a-f]+: 00000000/);
  else assert.doesNotMatch(text,/instruction at interruption/);
  for(let index=1;index<instructions.length;index++)assert.equal(BigInt(instructions[index][1])-BigInt(instructions[index-1][1]),4n);
 }
 const saved=run(binary,['records']);
 assert.match(saved.stdout,/PASS report-time instruction words, unreadable PC, once-only and mismatched signal handling preserve errno/);
 assert.equal((saved.stderr.match(/fatal signal /g)||[]).length,2,saved.stderr);
 assert.match(saved.stderr,/x0\s+0x000000000000aabb/);assert.match(saved.stderr,/x28\s+0x000000000000ccdd/);
 assert.match(saved.stderr,/instruction words at fatal report \(saved pc 0x[0-9a-f]+\)/);
 assert.match(saved.stderr,/insn 0x[0-9a-f]+: 22222222 pc/);
 assert.match(saved.stderr,/instruction at interruption 0x[0-9a-f]+: 11111111/);
 assert.equal((saved.stderr.match(/insn 0x[0-9a-f]+: unreadable kr=/g)||[]).length,9,saved.stderr);
 assert.match(saved.stderr,/insn 0x0000000000010000: unreadable kr=\d+ bytes=0 pc/);
 const off=run(binary,['segv-off']);
 assert.match(off.stdout,/PASS actual handled protection fault resumed with original errno/);
 assert.doesNotMatch(off.stderr,/handled protection fault|fatal signal/);
 const handled=run(binary,['segv-on']);
 assert.match(handled.stdout,/PASS actual handled protection fault resumed with original errno/);
 assert.equal((handled.stderr.match(/handled protection fault/g)||[]).length,1,handled.stderr);
 assert.match(handled.stderr,/signal=0x000000000000000b code=0x0000000000000002 guest_tid=0x00000000000002cf/);
 assert.match(handled.stderr,/pc=0x[0-9a-f]+ lr=0x[0-9a-f]+ fp=0x[0-9a-f]+ sp=0x[0-9a-f]+/);
 assert.match(handled.stderr,/instruction=0x00000000f9000020/);
 assert.match(handled.stderr,/x0=0x0000000000001122/);assert.match(handled.stderr,/x5=0x0000000000005566/);assert.match(handled.stderr,/x16=0x0000000000007788/);assert.match(handled.stderr,/x28=0x[0-9a-f]+/);
 assert.doesNotMatch(handled.stderr,/fatal signal/);
 const bounds=run(binary,['segv-bounds']);
 assert.match(bounds.stdout,/PASS handled context is opt-in, protection-only, bounded and safe after diagnostic retirement/);
 assert.equal((bounds.stderr.match(/handled protection fault/g)||[]).length,16,bounds.stderr);
 assert.equal((bounds.stderr.match(/instruction=unreadable/g)||[]).length,16,bounds.stderr);
 const abort=run(binary,['abort']);
 assert.match(abort.stdout,/PASS software abort uses only the current live guest syscall context and preserves errno/);
 assert.equal((abort.stderr.match(/fatal software SIGABRT/g)||[]).length,1,abort.stderr);
 assert.match(abort.stderr,/syscall 131 guest tid 719/);
 assert.match(abort.stderr,/host process \d+ pthread 0x[0-9a-f]+/);
 assert.match(abort.stderr,/x0\s+0x000000000000aabb/);
 assert.match(abort.stderr,/x28\s+0x000000000000ccdd/);
 assert.match(abort.stderr,/insn 0x[0-9a-f]+: d503201f pc/);
 const request=run(binary,['abort-request']);
 assert.match(request.stdout,/PASS abort request capture is opt-in, live self-only, bounded and safe after diagnostic retirement/);
 assert.equal((request.stderr.match(/software SIGABRT request/g)||[]).length,16,request.stderr);
 assert.match(request.stderr,/guest_tid=0x00000000000002cf/);
 assert.match(request.stderr,/pc=0x0000000011223344 stub=0x0000000055667788 lr=0x00000000aabbccdd/);
 assert.equal((request.stderr.match(/return0=0x0000000012345678/g)||[]).length,16,request.stderr);
 assert.doesNotMatch(request.stderr,/fatal|return1=/);
 const queued=run(binary,['abort-queued-request']);
 assert.match(queued.stdout,/PASS original queued abort syscall preserves siginfo, errors, errno and other-thread delivery with one opt-in self request/);
 assert.equal((queued.stderr.match(/software SIGABRT request/g)||[]).length,1,queued.stderr);
 assert.match(queued.stderr,/syscall=0x00000000000000f0/);
 assert.match(queued.stderr,/pc=0x0000000011223344 stub=0x0000000055667788 lr=0x00000000aabbccdd/);
 assert.doesNotMatch(queued.stderr,/fatal/);
 const host=run(binary,['host-syscall']);
 assert.match(host.stderr,/live guest syscall 135 tid 719/);
 assert.match(host.stderr,/guest arguments: x0 0x2 x1 0x6359c40 x2 0x0 x3 0x8/);
});
