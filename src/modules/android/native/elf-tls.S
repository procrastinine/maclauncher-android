/* AArch64 ELF TLSDESC calls preserve every register except x0 and NZCV.
 * A normal C call also clobbers x1-x18 and vector registers, so the signed
 * host veneer saves them before resolving the DTV. It does not borrow x18. */
.text
.p2align 2
.globl _klj_elf_tls_resolver
_klj_elf_tls_resolver:
    sub sp,sp,#688
    stp x1,x2,[sp,#0]
    stp x3,x4,[sp,#16]
    stp x5,x6,[sp,#32]
    stp x7,x8,[sp,#48]
    stp x9,x10,[sp,#64]
    stp x11,x12,[sp,#80]
    stp x13,x14,[sp,#96]
    stp x15,x16,[sp,#112]
    stp x17,x18,[sp,#128]
    stp x29,x30,[sp,#144]
    add x29,sp,#144
    stp q0,q1,[sp,#160]
    stp q2,q3,[sp,#192]
    stp q4,q5,[sp,#224]
    stp q6,q7,[sp,#256]
    stp q8,q9,[sp,#288]
    stp q10,q11,[sp,#320]
    stp q12,q13,[sp,#352]
    stp q14,q15,[sp,#384]
    stp q16,q17,[sp,#416]
    stp q18,q19,[sp,#448]
    stp q20,q21,[sp,#480]
    stp q22,q23,[sp,#512]
    stp q24,q25,[sp,#544]
    stp q26,q27,[sp,#576]
    stp q28,q29,[sp,#608]
    stp q30,q31,[sp,#640]
    mrs x9,fpcr
    mrs x10,fpsr
    stp x9,x10,[sp,#672]
    ldr x0,[x0,#8]
    bl _klj_elf_tls_descriptor
    ldp q0,q1,[sp,#160]
    ldp q2,q3,[sp,#192]
    ldp q4,q5,[sp,#224]
    ldp q6,q7,[sp,#256]
    ldp q8,q9,[sp,#288]
    ldp q10,q11,[sp,#320]
    ldp q12,q13,[sp,#352]
    ldp q14,q15,[sp,#384]
    ldp q16,q17,[sp,#416]
    ldp q18,q19,[sp,#448]
    ldp q20,q21,[sp,#480]
    ldp q22,q23,[sp,#512]
    ldp q24,q25,[sp,#544]
    ldp q26,q27,[sp,#576]
    ldp q28,q29,[sp,#608]
    ldp q30,q31,[sp,#640]
    ldp x9,x10,[sp,#672]
    msr fpcr,x9
    msr fpsr,x10
    ldp x1,x2,[sp,#0]
    ldp x3,x4,[sp,#16]
    ldp x5,x6,[sp,#32]
    ldp x7,x8,[sp,#48]
    ldp x9,x10,[sp,#64]
    ldp x11,x12,[sp,#80]
    ldp x13,x14,[sp,#96]
    ldp x15,x16,[sp,#112]
    ldp x17,x18,[sp,#128]
    ldp x29,x30,[sp,#144]
    add sp,sp,#688
    ret
